"""State-space model analysis (criterion A): controllability, observability, LQR poles.

Run:  python -m src.analysis.model_analysis      (writes results/model_analysis.md)

1. Kinematic model linearised at rest:  x_dot = B(theta) u, A = 0
      rank [B, AB, A^2B] = 2 < 3  -> NOT controllable (nonholonomic; Brockett).
2. Tracking-error model about a moving reference (v_r, w_r):
      controllable iff v_r != 0 or w_r != 0 -> LQR is designed on this model and
      the gain is scheduled on (v_r, w_r) with |v_r| >= v_min.
3. Observability of the EKF (discrete, linearised F_k, H_k):
      odometry only (no H)                 -> rank 0 (pose unobservable, drift)
      one landmark, [r, b], static          -> rank 2 (unobservable direction)
      one landmark, [r, b], moving          -> rank 2 (still! rotation about the landmark)
      one landmark, [r, b, alpha]           -> rank 3 even when static
      two landmarks, [r, b], static         -> rank 3
   The local observability matrix O = [H; H F; H F^2] is evaluated numerically.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from src.config import RESULTS, make_config  # noqa: E402
from src.control.lqr_tracker import LQRTracker, error_dynamics  # noqa: E402
from src.estimation.ekf import LandmarkEKF  # noqa: E402


def ctrb(A, B):
    n = A.shape[0]
    return np.hstack([np.linalg.matrix_power(A, k) @ B for k in range(n)])


def local_obsv(ekf: LandmarkEKF, x0, v, w, dt, landmarks, steps=3, dim=3):
    x = np.array(x0, float)
    rows = []
    Phi = np.eye(3)
    for _ in range(steps):
        for lm in landmarks:
            rows.append(ekf.H(x, lm, dim) @ Phi)
        F, _ = ekf.jacobians(x, v, w, dt)
        Phi = F @ Phi
        x = ekf.motion(x, v, w, dt)
    O = np.vstack(rows) if rows else np.zeros((0, 3))
    return O


def rank(M, tol=1e-9):
    return int(np.linalg.matrix_rank(M, tol)) if M.size else 0


def null_dir(M):
    if not M.size:
        return "all"
    _, s, vt = np.linalg.svd(M)
    if (s > 1e-9).sum() >= 3:
        return "-"
    v = vt[-1]
    return "[" + ", ".join(f"{c:+.2f}" for c in v) + "]"


def main() -> str:
    cfg = make_config()
    out = ["# Model analysis (generated by `python -m src.analysis.model_analysis`)\n"]

    # 1. at rest
    th = 0.3
    A0 = np.zeros((3, 3))
    B0 = np.array([[math.cos(th), 0], [math.sin(th), 0], [0, 1]])
    out.append("## 1. Unicycle linearised at rest\n")
    out.append(f"A = 0, B(theta) = [[cos th, 0], [sin th, 0], [0, 1]] -> rank C = **{rank(ctrb(A0, B0))}** of 3 "
               "(not controllable: no instantaneous lateral motion).\n")

    # 2. error dynamics
    out.append("## 2. Tracking-error model (LQR design model)\n")
    out.append("| v_r [m/s] | w_r [rad/s] | rank C | controllable |\n|---|---|---|---|")
    for vr, wr in [(0.0, 0.0), (0.0, 0.5), (0.05, 0.0), (0.18, 0.0), (0.18, 0.6)]:
        A, B = error_dynamics(vr, wr)
        r = rank(ctrb(A, B))
        out.append(f"| {vr} | {wr} | {r} | {'yes' if r == 3 else 'NO'} |")
    tr = LQRTracker(cfg.lqr, cfg.robot, cfg.sim.control_dt)
    out.append(f"\nBryson weights: Q = diag({', '.join(f'{q:.0f}' for q in np.diag(tr.Q))}), "
               f"R = diag({', '.join(f'{r:.1f}' for r in np.diag(tr.R))}), dt = {cfg.sim.control_dt} s\n")
    out.append("| v_r | w_r | K (2x3) | closed-loop eigenvalue magnitude (discrete) | continuous-equivalent poles [1/s] |\n|---|---|---|---|---|")
    for vr, wr in [(0.03, 0.0), (0.08, 0.0), (0.18, 0.0), (0.18, 0.5)]:
        K = tr.gain(vr, wr)
        z = tr.closed_loop_poles(vr, wr)
        s = np.log(z.astype(complex)) / cfg.sim.control_dt
        out.append(f"| {vr} | {wr} | {np.array2string(K, precision=2, suppress_small=True).replace(chr(10), '')} | "
                   f"{', '.join(f'{abs(p):.3f}' for p in z)} | {', '.join(f'{p.real:.2f}{p.imag:+.2f}j' for p in s)} |")

    # 3. observability
    ekf = LandmarkEKF(cfg.ekf, np.zeros(3))
    lm1 = np.array([2.0, 0.5, math.pi, 0.2])
    lm2 = np.array([-1.0, 2.5, -math.pi / 2, 0.2])
    out.append("\n## 3. Local observability of the EKF model\n")
    out.append("| sensors | motion | rank O | unobservable direction (x, y, theta) |\n|---|---|---|---|")
    cases = [
        ("odometry only", "moving", [], 2, 0.18, 0.3),
        ("1 marker [r, b]", "static", [lm1], 2, 0.0, 0.0),
        ("1 marker [r, b]", "moving", [lm1], 2, 0.18, 0.3),
        ("1 marker [r, b, alpha]", "static", [lm1], 3, 0.0, 0.0),
        ("2 markers [r, b]", "static", [lm1, lm2], 2, 0.0, 0.0),
    ]
    for name, mot, lms, dim, v, w in cases:
        O = local_obsv(ekf, [0.0, 0.0, 0.3], v, w, 0.5, lms, steps=3, dim=dim)
        out.append(f"| {name} | {mot} | {rank(O)} | {null_dir(O)} |")
    out.append("\nWith a single point landmark measured in range and bearing the unobservable direction is a "
               "rotation of the robot's pose about the landmark (position moves along the circle around the "
               "marker and the heading turns by the same angle). Odometry is expressed in the body frame, so this "
               "rotation leaves every future measurement unchanged: **motion does not remove it**. The PnP relative "
               "heading alpha (the marker's orientation is known in the map) or a second marker does. This is why "
               "the dock approach uses z = [r, b, alpha] when the marker is large enough in the image, and why the "
               "room has extra wall markers. Odometry alone observes nothing absolute: the covariance grows without "
               "bound until a marker is seen (see the estimation plots / odom_only scenario).\n")
    text = "\n".join(out)
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "model_analysis.md").write_text(text)
    print(text)
    return text


if __name__ == "__main__":
    main()
